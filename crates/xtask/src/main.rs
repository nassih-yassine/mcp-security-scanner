//! Repository maintenance tasks. `cargo xtask gen-docs [--check]`.

use std::path::{Path, PathBuf};

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let result = match args.first().map(String::as_str) {
        Some("gen-docs") => gen_docs(args.iter().any(|a| a == "--check")),
        Some(other) => Err(format!("unknown task: {other}")),
        None => Err("usage: cargo xtask gen-docs [--check]".to_string()),
    };
    if let Err(message) = result {
        eprintln!("{message}");
        std::process::exit(1);
    }
}

fn rules_index() -> String {
    let mut out =
        String::from("# Rule index\n\nGenerated by `cargo xtask gen-docs`. Do not edit.\n\n");
    out.push_str("| Rule | Severity | Confidence | Since | Docs |\n|---|---|---|---|---|\n");
    for rule in mcpscan_core::rules::registry() {
        out.push_str(&format!(
            "| `{}` | {} | {} | {} | [docs](../rules/{}.md) |\n",
            rule.id,
            serde_json::to_string(&rule.severity)
                .unwrap_or_default()
                .trim_matches('"'),
            serde_json::to_string(&rule.confidence)
                .unwrap_or_default()
                .trim_matches('"'),
            rule.since,
            rule.id
        ));
    }
    out
}

fn readme_rules_block() -> String {
    let mut out = String::from("<!-- BEGIN RULES -->\n");
    out.push_str("| Rule | Severity | Confidence |\n|---|---|---|\n");
    for rule in mcpscan_core::rules::registry() {
        out.push_str(&format!(
            "| `{}` | {} | {} |\n",
            rule.id,
            serde_json::to_string(&rule.severity)
                .unwrap_or_default()
                .trim_matches('"'),
            serde_json::to_string(&rule.confidence)
                .unwrap_or_default()
                .trim_matches('"'),
        ));
    }
    out.push_str("<!-- END RULES -->\n");
    out
}

fn replace_block(document: &str, begin: &str, end: &str, replacement: &str) -> String {
    let Some(start) = document.find(begin) else {
        return document.to_string();
    };
    let Some(stop) = document.find(end) else {
        return document.to_string();
    };
    let mut out = String::new();
    out.push_str(&document[..start]);
    out.push_str(replacement.trim_end_matches('\n'));
    out.push_str(&document[stop + end.len()..]);
    out
}

fn gen_docs(check: bool) -> Result<(), String> {
    let root = root();
    let mut stale = Vec::new();

    let index_path = root.join("docs/generated/rules-index.md");
    let index = rules_index();
    if std::fs::read_to_string(&index_path).ok().as_deref() != Some(index.as_str()) {
        stale.push(index_path.clone());
        if !check {
            std::fs::create_dir_all(index_path.parent().unwrap()).map_err(|e| e.to_string())?;
            std::fs::write(&index_path, &index).map_err(|e| e.to_string())?;
        }
    }

    let readme_path = root.join("README.md");
    if let Ok(readme) = std::fs::read_to_string(&readme_path) {
        let updated = replace_block(
            &readme,
            "<!-- BEGIN RULES -->",
            "<!-- END RULES -->",
            &readme_rules_block(),
        );
        if updated != readme {
            stale.push(readme_path.clone());
            if !check {
                std::fs::write(&readme_path, updated).map_err(|e| e.to_string())?;
            }
        }
    }

    if check && !stale.is_empty() {
        let list: Vec<String> = stale.iter().map(|p| p.display().to_string()).collect();
        return Err(format!(
            "generated docs are stale:\n  {}",
            list.join("\n  ")
        ));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    #[test]
    fn every_registered_rule_has_a_doc_page() {
        for rule in mcpscan_core::rules::registry() {
            assert!(
                root().join(rule.docs).exists(),
                "{} -> {}",
                rule.id,
                rule.docs
            );
        }
    }

    #[test]
    fn every_doc_page_maps_to_a_registered_rule() {
        let ids: BTreeSet<&str> = mcpscan_core::rules::registry()
            .iter()
            .map(|r| r.id)
            .collect();
        for entry in std::fs::read_dir(root().join("docs/rules")).unwrap() {
            let path = entry.unwrap().path();
            let stem = path.file_stem().unwrap().to_string_lossy().to_string();
            assert!(ids.contains(stem.as_str()), "orphan doc page {stem}");
        }
    }

    #[test]
    fn every_rule_has_fixtures_and_expected_output() {
        for rule in mcpscan_core::rules::registry() {
            let dir = root().join("fixtures").join(rule.id);
            assert!(dir.join("expected.json").exists(), "{}", rule.id);
            assert!(dir.join("vulnerable.json").exists(), "{}", rule.id);
            assert!(dir.join("clean.json").exists(), "{}", rule.id);
        }
    }

    #[test]
    fn front_matter_matches_code() {
        for rule in mcpscan_core::rules::registry() {
            let page = std::fs::read_to_string(root().join(rule.docs)).unwrap();
            let severity = serde_json::to_string(&rule.severity).unwrap();
            assert!(
                page.contains(&format!("severity: {}", severity.trim_matches('"'))),
                "{}",
                rule.id
            );
            assert!(
                page.contains(&format!("since: {}", rule.since)),
                "{}",
                rule.id
            );
        }
    }

    #[test]
    fn check_mode_detects_drift() {
        assert!(gen_docs(false).is_ok());
        assert!(gen_docs(true).is_ok());
        let path = root().join("docs/generated/rules-index.md");
        let original = std::fs::read_to_string(&path).unwrap();
        std::fs::write(&path, "drift").unwrap();
        assert!(gen_docs(true).is_err());
        std::fs::write(&path, original).unwrap();
    }
}
